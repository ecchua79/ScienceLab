/* ---------- 血流粒子 ---------- */
const flowGroup = new THREE.Group();
scene.add(flowGroup);
let flowParticles = [];   // 每个元素：{ head: Mesh, trail: Mesh[], curve, t, speed, color }

/* 生成圆形粒子贴图：实心圆芯 + 柔和外晕（中心保持饱和色，不会被背景冲淡） */
function makeParticleTexture() {
  const S = 64;
  const cv = document.createElement('canvas');
  cv.width = cv.height = S;
  const g = cv.getContext('2d');
  const c = S / 2;

  // 外层柔光
  const glow = g.createRadialGradient(c, c, S * 0.16, c, c, S * 0.5);
  glow.addColorStop(0,   'rgba(255,255,255,0.42)');
  glow.addColorStop(0.55,'rgba(255,255,255,0.14)');
  glow.addColorStop(1,   'rgba(255,255,255,0)');
  g.fillStyle = glow;
  g.fillRect(0, 0, S, S);

  // 实心圆芯
  g.beginPath();
  g.arc(c, c, S * 0.19, 0, Math.PI * 2);
  g.fillStyle = 'rgba(255,255,255,1)';
  g.fill();

  const tex = new THREE.CanvasTexture(cv);
  tex.colorSpace = THREE.SRGBColorSpace;
  return tex;
}

function buildFlow() {
  flowGroup.clear();
  flowParticles = [];

  const tex = makeParticleTexture();

  // 模型逆矩阵：把世界坐标的粒子还原到 FBX 局部坐标，用于心腔命中判定
  const invMat = new THREE.Matrix4();
  if (modelRoot) {
    modelRoot.updateMatrixWorld(true);
    invMat.copy(modelRoot.matrixWorld).invert();
  }

  for (const path of FLOW_PATHS) {
    const curve = new THREE.CatmullRomCurve3(
      path.pts.map(p => new THREE.Vector3(p[0], p[1], p[2]).multiplyScalar(modelScale).add(modelCenter)),
      false, 'catmullrom', 0.35
    );

    // 每条路径放 N 组粒子，每组 = 1 个头 + 3 个拖尾
    // 4 条路径 × 24 组 = 96 组：组数足够多时，心腔段（权重高）能同时被
    // 多组粒子覆盖，视觉上呈现"血流在心腔内持续涌动"而非稀疏闪点；
    // 同时保证长血管段（主动脉弓、降主动脉、肺动脉分支）也有连续可见的粒子流
    const GROUPS = 56;
    const TRAIL = 4;
    const headSize = 0.052 * modelScale;
    const trailSize = [0.036, 0.026, 0.018, 0.012];  // 逐渐缩小

    /* --- 关键：按"教学重点"分配粒子，而非沿弧长均匀分布 ---
       心腔段（房室瓣前后）在弧长中占比很小，若均匀分布则心内粒子稀疏、
       看不到"血流经心房→心室"的过程。这里给心腔段加更高权重，
       让更多粒子停留在心脏内部。
       keySegs 用「控制点索引」标注心腔段（CatmullRom 的段参数 u = i/(n-1)，
       与索引线性对应，便于换算）。 */
    const nPts = path.pts.length;
    const KEY = (path.keySegs || []).map(([i0, i1]) => [
      Math.max(0, Math.min(1, i0 / (nPts - 1))),
      Math.max(0, Math.min(1, i1 / (nPts - 1)))
    ]);
    const DENSITY = path.density || 3.4;   // 心腔段粒子密度倍率（实际用 path.density: 1.55~1.65）

    // 构建权重累积表（基于段参数 u）
    const WSTEP = 160;
    const wTab = new Float32Array(WSTEP + 1);
    let w = 0;
    for (let i = 0; i <= WSTEP; i++) {
      const u = i / WSTEP;
      let mult = 1;
      for (const [a, b] of KEY) if (u >= a && u <= b) mult = DENSITY;
      w += mult / WSTEP;
      wTab[i] = w;
    }
    const wTotal = wTab[WSTEP];
    for (let i = 0; i <= WSTEP; i++) wTab[i] /= wTotal;

    // 权重 → 段参数 u 的反查表
    const uOfW = new Float32Array(WSTEP + 1);
    {
      let j = 0;
      for (let i = 0; i <= WSTEP; i++) {
        const target = i / WSTEP;
        while (j < WSTEP && wTab[j + 1] < target) j++;
        const seg = wTab[j + 1] - wTab[j];
        const frac = seg > 1e-9 ? (target - wTab[j]) / seg : 0;
        uOfW[i] = (j + frac) / WSTEP;
      }
    }
    // 第 g 组粒子放在权重空间的第 g/GROUPS 处（权重均匀 → 心腔段粒子更多）
    const startW = [];
    for (let g = 0; g < GROUPS; g++) startW.push(g / GROUPS);

    for (let g = 0; g < GROUPS; g++) {
      // 外圈：彩色光晕（大而暗）
      const haloMat = new THREE.SpriteMaterial({
        map: tex, color: path.color, transparent: true, opacity: 0.55,
        depthTest: false, depthWrite: false, toneMapped: false,
        blending: THREE.AdditiveBlending
      });
      const halo = new THREE.Sprite(haloMat);
      halo.scale.setScalar(headSize * 2.1);
      halo.renderOrder = 9;
      flowGroup.add(halo);

      // 核心：亮白（保证任何背景下都能看清）
      const headMat = new THREE.SpriteMaterial({
        map: tex, color: 0xffffff, transparent: true, opacity: 1.0,
        depthTest: false, depthWrite: false, toneMapped: false
      });
      const head = new THREE.Sprite(headMat);
      head.scale.setScalar(headSize);
      head.renderOrder = 11;
      flowGroup.add(head);

      const trail = [];
      for (let k = 0; k < TRAIL; k++) {
        const tm = new THREE.SpriteMaterial({
          map: tex, color: path.color, transparent: true,
          opacity: 0.62 - k * 0.11,
          depthTest: false, depthWrite: false, toneMapped: false,
          blending: THREE.AdditiveBlending
        });
        const ts = new THREE.Sprite(tm);
        ts.scale.setScalar(trailSize[k] * modelScale);
        ts.renderOrder = 10;
        flowGroup.add(ts);
        trail.push(ts);
      }

      flowParticles.push({
        head, halo, trail, curve,
        w: startW[g],           // 权重空间位置 0→1
        speed: 0.075,
        color: path.color,
        headSize, trailSize,
        glow: 1,               // 心腔内粒子放大提亮的过渡系数
        invMat,                // 用于心腔命中判定
        uOfW, WSTEP            // 权重空间 → 段参数 u 的反查表
      });
    }
  }
  flowGroup.visible = false;

  flowInfo.innerHTML =
    `<b>血流动画</b>` +
    `<span class="ln"><span class="red">● 红色粒子</span> 充氧血：肺静脉 → 左心房 → 左心室 → 主动脉 → 全身</span>` +
    `<span class="ln"><span class="blue">● 蓝色粒子</span> 缺氧血：上下腔静脉 → 右心房 → 右心室 → 肺动脉 → 肺部</span>`;
  flowInfo.classList.toggle('show', flowOn);
}

const _fp = new THREE.Vector3();

/* 权重空间位置 w (0→1) → 段参数 u：查 uOfW 反查表
   注意：u 必须落在 [0,1]，否则 CatmullRomCurve3.getPoint 会取到越界点报
   "Cannot read properties of undefined (reading 'x')" */
function wToU(fp, w) {
  const { uOfW, WSTEP } = fp;
  const ww = Math.max(0, Math.min(1, w));
  const idx = ww * WSTEP;
  const i = Math.min(WSTEP - 1, Math.floor(idx));
  const frac = idx - i;
  const u = uOfW[i] + (uOfW[i + 1] - uOfW[i]) * frac;
  return Math.max(0, Math.min(1, u));
}

/* 心腔中心（FBX 局部坐标）——用于判断粒子是否正在心腔内，
   心腔内粒子放大 + 提亮，形成"心腔内血流涌动"的视觉焦点 */
const CHAMBER_CENTERS = [
  new THREE.Vector3(-0.30, 0.20, -0.15),   // 左心房 LA
  new THREE.Vector3(-0.06, -0.28, -0.40),  // 左心室 LV
  new THREE.Vector3( 0.20, 0.22,  0.22),   // 右心房 RA
  new THREE.Vector3( 0.10, -0.16, 0.42),   // 右心室 RV
];
const CHAMBER_R = 0.19;
const _lp = new THREE.Vector3();

function inChamber(worldPos, invMat) {
  if (!invMat) return false;
  _lp.copy(worldPos).applyMatrix4(invMat);
  for (const c of CHAMBER_CENTERS) {
    if (_lp.distanceTo(c) < CHAMBER_R) return true;
  }
  return false;
}

function updateFlow(dt) {
  if (!flowOn) return;
  for (const fp of flowParticles) {
    const curve = fp.curve;
    // 在权重空间匀速推进：心腔段权重高 → 粒子在心脏内部停留更久，
    // 视觉上就是"血流在心腔里流转"，而不是一闪而过
    fp.w += dt * fp.speed;
    if (fp.w > 1) fp.w -= 1;

    // 头粒子
    curve.getPoint(wToU(fp, fp.w), _fp);
    fp.head.position.copy(_fp);

    // 拖尾：在权重空间回退一小段（与头粒子保持同速的相对距离）
    const trailGap = 0.020;
    for (let k = 0; k < fp.trail.length; k++) {
      let tw = fp.w - trailGap * (k + 1);
      if (tw < 0) tw += 1;
      curve.getPoint(wToU(fp, tw), _fp);
      fp.trail[k].position.copy(_fp);
    }

    // 心腔内粒子放大提亮 —— 让"血流在心腔内"成为视觉焦点
    const inside = inChamber(fp.head.position, fp.invMat);
    const target = inside ? 1.55 : 1.0;
    fp.glow = fp.glow + (target - fp.glow) * Math.min(1, dt * 7);
    const s = fp.headSize * fp.glow;
    fp.head.scale.setScalar(s);
    fp.head.material.opacity = 1.0 * (inside ? 1 : 0.88);
    if (fp.halo) {
      fp.halo.position.copy(fp.head.position);
      fp.halo.scale.setScalar(s * 2.1);
      fp.halo.material.opacity = 0.42 + 0.22 * (fp.glow - 1) / 0.55;
    }
    for (let k = 0; k < fp.trail.length; k++) {
      fp.trail[k].scale.setScalar(fp.trailSize[k] * modelScale * fp.glow);
    }
  }
}

/* ---------- 心跳搏动 ---------- */
let beatT = 0;
const myoMesh = () => meshMap.get('myo');
const septumMesh = () => meshMap.get('septum');
const avvMesh = () => meshMap.get('avvalve');

function updateBeat(dt) {
  if (!beatOn || !modelRoot) return;
  beatT += dt;
  const period = 0.86;                       // ~70 bpm
  const ph = (beatT % period) / period;

  // 心动周期：心房收缩(0-0.15) → 等容收缩(0.15-0.22) → 射血(0.22-0.42) → 等容舒张(0.42-0.5) → 充盈(0.5-1)
  let sys = 0;
  if (ph >= 0.15 && ph < 0.45) {
    const u = (ph - 0.15) / 0.30;
    sys = Math.sin(u * Math.PI) ** 0.72;      // 心室收缩曲线
  }
  let atr = 0;
  if (ph >= 0.82 && ph < 0.97) {
    const u = (ph - 0.82) / 0.15;
    atr = Math.sin(u * Math.PI) * 0.5;        // 心房收缩（较轻）
  }

  // 心室：沿长轴缩短 + 径向收缩
  const myo = myoMesh();
  if (myo) {
    myo.scale.set(
      1 - sys * 0.085 + atr * 0.012,
      1 - sys * 0.115 + atr * 0.020,
      1 - sys * 0.085 + atr * 0.012
    );
    myo.position.y = modelCenter.y + (myo.userData._baseY ?? (myo.userData._baseY = myo.position.y)) - modelCenter.y;
  }
  const sep = septumMesh();
  if (sep) {
    sep.scale.set(1 - sys * 0.055, 1 - sys * 0.085, 1 - sys * 0.055);
  }
  // 房室瓣随心室收缩略微下移
  const av = avvMesh();
  if (av) {
    const base = av.userData._baseY ?? (av.userData._baseY = av.position.y);
    av.position.y = base - sys * 0.012;
  }
  // 冠状动脉：随心肌收缩而轻微挤压（径向收缩 + 整体微缩）
  // 冠脉贴附于心肌表面，心室收缩时被压迫变细，舒张时充盈恢复
  const avr = meshMap.get('avr');
  if (avr) {
    const baseScale = avr.userData._beatBase ?? 1;
    // 收缩时冠脉轻微变细（约4%），与心肌同步但有延迟感
    const avrSys = sys * 0.04;
    const s = baseScale - avrSys;
    avr.scale.set(s, s * (1 - sys * 0.02), s);
  }
}

/* ---------- 传导系统 ---------- */
const conductionGroup = new THREE.Group();
scene.add(conductionGroup);
let condLine = null, condDot = null, condMat = null;

function applyConduction() {
  const cond = meshMap.get('cond');
  if (!cond) return;
  cond.visible = conductionOn;
  if (condMat) { condMat.opacity = conductionOn ? 1 : 0; }
}

function buildConduction() {
  // 用传导系统网格自身的点云构建一条可视路径（取稀疏采样连成折线）
  const cond = meshMap.get('cond');
  if (!cond) return;
  const pos = cond.geometry.attributes.position;
  // 采样若干顶点，按 y 排序做简易路径
  const pts = [];
  const step = Math.max(1, Math.floor(pos.count / 240));
  for (let i = 0; i < pos.count; i += step) {
    pts.push(new THREE.Vector3().fromBufferAttribute(pos, i));
  }
  // 过滤离群点，保留躯干范围
  const filtered = pts.filter(p => p.length() < 2.2);
  filtered.sort((a,b) => a.y - b.y);
  const pathPts = filtered.filter((_, i) => i % Math.max(1, Math.floor(filtered.length/40)) === 0);
  if (pathPts.length < 3) return;

  const curve = new THREE.CatmullRomCurve3(pathPts, false, 'catmullrom', 0.3);
  const geo = new THREE.BufferGeometry().setFromPoints(curve.getPoints(120));
  condMat = new THREE.LineBasicMaterial({ color: 0xffd54f, transparent:true, opacity: conductionOn ? 1 : 0 });
  condLine = new THREE.Line(geo, condMat);
  conductionGroup.add(condLine);

  const dg = new THREE.SphereGeometry(0.035 * modelScale, 12, 12);
  condDot = new THREE.Mesh(dg, new THREE.MeshBasicMaterial({ color: 0xfff59d }));
  condDot.position.copy(curve.getPointAt(0));
  conductionGroup.add(condDot);
  conductionGroup.visible = false;
}

let condT = 0;
function updateConduction(dt) {
  if (!conductionOn || !condLine) return;
  condT += dt;
  const u = (condT * 0.32) % 1;
  const c = condLine.geometry.attributes.position;
  const total = c.count;
  // 让一段"亮带"沿线传播
  const band = 0.13;
  const colors = condLine.geometry.getAttribute('color');
  if (!colors) {
    condLine.geometry.setAttribute('color',
      new THREE.BufferAttribute(new Float32Array(total * 3), 3));
  }
  const ca = condLine.geometry.attributes.color;
  for (let i = 0; i < total; i++) {
    const p = i / (total - 1);
    let d = Math.abs(p - u);
    if (d > 0.5) d = 1 - d;
    const k = Math.max(0, 1 - d / band);
    const glow = 0.28 + 0.72 * k;
    ca.setXYZ(i, 1.0 * glow, 0.84 * glow, 0.31 * glow);
  }
  ca.needsUpdate = true;
  // 让亮点沿曲线移动
  if (condDot && total > 1) {
    const idx = Math.floor(u * (total - 1));
    condDot.position.set(
      c.getX(idx),
      c.getY(idx),
      c.getZ(idx)
    );
  }
}

/* ---------- 透视心肌 ---------- */
function applyXray() {
  // 透视目标：心肌、室间隔、冠状动脉（均为心肌相关结构）
  const myo = meshMap.get('myo');
  const sep = meshMap.get('septum');
  const avr = meshMap.get('avr');           // 冠状动脉
  for (const m of [myo, sep, avr]) {
    if (!m) continue;
    const mats = Array.isArray(m.material) ? m.material : [m.material];
    for (const mm of mats) {
      if (!mm) continue;
      if (xrayOn) {
        // 透视态：心肌/冠脉近乎透明，压暗其自发光 → 粉/青色粒子在暗背景上强烈突出
        mm.transparent = true;
        mm.opacity = 0.10;
        mm.depthWrite = false;
        mm.side = THREE.DoubleSide;
        if (mm.emissive) {
          if (!mm.userData._xrayEm) mm.userData._xrayEm = mm.emissive.clone();
          mm.emissive.setHex(0x000000);
        }
      } else {
        mm.transparent = false;
        mm.opacity = 1;
        mm.depthWrite = true;
        mm.side = THREE.FrontSide;
        if (mm.emissive && mm.userData._xrayEm) {
          mm.emissive.copy(mm.userData._xrayEm);
        }
      }
      mm.needsUpdate = true;
    }
  }
}

