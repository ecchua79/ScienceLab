/* ---------- 动画循环 ---------- */
const clock = new THREE.Clock();

/* 截图钩子：URL 里带 shot=<name> 时，在渲染帧内抓取 canvas 并 POST 回本地截图服务。
   必须在 renderer.render() 之后、同一帧内抓，否则 WebGL 缓冲已被清空。
   抓到的 PNG 会 POST 到 http://<host>/upload?name=<name> */
let _shotDone = false;
function maybeShot() {
  if (_shotDone) return;
  let name = null;
  try {
    const h = new URLSearchParams(location.hash.slice(1));
    name = h.get('shot');
  } catch (e) { return; }
  if (!name) { _shotDone = true; return; }
  const c = renderer.domElement;
  try {
    const url = c.toDataURL('image/png');
    fetch('/upload?name=' + encodeURIComponent(name), { method: 'POST', body: url })
      .then(() => { _shotDone = true; })
      .catch(() => { _shotDone = true; });
  } catch (e) { _shotDone = true; }
}

function animate() {
  requestAnimationFrame(animate);
  const dt = Math.min(clock.getDelta(), 0.05);
  controls.update();
  updateBeat(dt);
  updateFlow(dt);
  updateConduction(dt);
  updateLabels();
  renderer.render(scene, camera);
  maybeShot();
}
animate();

